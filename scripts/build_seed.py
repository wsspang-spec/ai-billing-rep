"""Build data/seed.json (the app's seed + the PDFs' content) from the team dataset data/demo_dataset.json.

demo_dataset.json stays the single source of truth (integer cents). Run: python scripts/build_seed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = json.loads((ROOT / "data" / "demo_dataset.json").read_text())
evals = [json.loads(x) for x in (ROOT / "evals" / "inputs.jsonl").read_text().splitlines() if x.strip()]
vendors = {v["id"]: v["name"] for v in src["vendors"]}
services = {s["id"]: s for s in src["services"]}
KIND = {"recurring": "service", "unclassified": "other", "one_time": "fee", "tax": "tax", "credit": "credit"}


def invoice(i: dict, file: str | None = None) -> dict:
    out = {
        "invoice_number": i["invoice_number"], "account": i["account_id"], "vendor": vendors[i["vendor_id"]],
        "period_start": i["period_start"], "period_end": i["period_end"], "invoice_date": i["invoice_date"], "due_date": i["due_date"],
        "total": i["amount_due_cents"] / 100,
        "lines": [{"line_no": n + 1, "line_id": l["id"], "description": l["description"], "service_id": l.get("service_id"),
                   "kind": KIND.get(l["charge_type"], "other"), "charge_type": l["charge_type"], "amount": l["amount_cents"] / 100}
                  for n, l in enumerate(i["lines"])],
    }
    if file:
        out["file"] = file
    return out


invoices = {i["id"]: i for i in src["invoices"]}
terms = []
priced = [d for d in src["documents"] if d.get("service_id") and d.get("amount_cents") and d["type"] in ("contract", "approved_amendment")]
for d in priced:
    later = sorted((x for x in priced if x["service_id"] == d["service_id"] and x["valid_from"] > d["valid_from"]), key=lambda x: x["valid_from"])
    nxt = later[0] if later else None
    valid_to = None
    if nxt:
        import datetime as dt

        valid_to = (dt.date.fromisoformat(nxt["valid_from"]) - dt.timedelta(days=1)).isoformat()
    terms.append({"id": f"term-{d['id']}", "service": d["service_id"], "item": "monthly_price", "value": d["amount_cents"] / 100,
                  "valid_from": d["valid_from"], "valid_to": valid_to, "recorded_at": d["recorded_at"], "source": d["id"],
                  "quote": d["text"], "superseded_by": f"term-{nxt['id']}" if nxt else None})

early = next(e for e in evals if e["inputs"]["invoice"]["id"] == "N-SEP-EARLY")["inputs"]["invoice"]
seed = {
    "_note": "Generated by scripts/build_seed.py from data/demo_dataset.json. All data is SYNTHETIC.",
    "company": src["company"],
    "as_of": src["as_of"],
    "user": {"email": "maria@atlas.example", "password": "demo-password", "name": "Maria Santos", "role": "AP specialist"},
    "accounts": [{"id": s["account_id"], "service": s["id"], "label": f"{s['location']} connectivity ({s['id']})", "site": s["location"]} for s in src["services"]],
    "documents": [{"id": d["id"], "kind": d["type"], "title": d["id"].replace("-", " ").title(), "date": d.get("recorded_at"),
                   "service_id": d.get("service_id"), "valid_from": d.get("valid_from"), "text": d["text"]} for d in src["documents"]],
    "terms": terms,
    "credits": [{"id": d["id"], "account": next(s["account_id"] for s in src["services"] if s["id"] == d["service_id"]),
                 "amount": d["amount_cents"] / 100, "state": "promised", "source": d["id"], "note": d["text"]}
                for d in src["documents"] if d["type"] == "vendor_message" and "credit" in d["id"]],
    "history": [invoice(i) | {"status": "Paid"} for i in src["invoices"] if i["period_start"] < "2026-10-01"],
    "inbox": [invoice(invoices[x], f"{x}.pdf") for x in src["initial_upload_ids"]],
    "portal_only": [invoice(invoices[x], f"{x}.pdf") for x in src["portal_only_invoice_ids"]],
    "expected_accounts": src["expected_october_accounts"],
    "eval_invoices": [invoice(early, "N-SEP-EARLY.pdf") | {"case": "E02 September $525 before the amendment"},
                      invoice(invoices["N-OCT-101"], "N-OCT-101-copy.pdf") | {"case": "E04 duplicate"}],
    "policy": src["policy"],
}
(ROOT / "data" / "seed.json").write_text(json.dumps(seed, indent=2))
print("wrote data/seed.json:", len(seed["terms"]), "terms,", len(seed["history"]), "history,", len(seed["inbox"]), "inbox")
